package io.github.hlcaptain.symbols.generator

/**
 * Renders named manifest catalogs as common Kotlin data.
 *
 * @param entriesPerChunk maximum number of catalog entries placed in one
 * generated helper before another helper is started
 * @throws IllegalArgumentException if [entriesPerChunk] is not positive
 */
class KotlinSymbolCatalogsRenderer(
    private val entriesPerChunk: Int = 200,
) {
    init {
        require(entriesPerChunk > 0) { "entriesPerChunk must be positive" }
    }

    /**
     * Renders one or more symbol catalogs as common Kotlin source text.
     *
     * Catalogs and entries are sorted before rendering, and large catalogs are
     * divided according to the renderer's configured chunk size. The generated
     * declarations are internal to their target module. This function builds
     * text in memory and does not read or write files.
     *
     * @param packageName Kotlin package for the generated source.
     * @param catalogs generated declaration name to validated catalog.
     * @return one relative Kotlin source path and its complete contents.
     * @throws IllegalArgumentException if [catalogs] is empty, a package or
     * catalog name is invalid, or two catalog names compile to the same getter
     * name.
     */
    fun render(
        packageName: String,
        catalogs: Map<String, SymbolCatalog>,
    ): RenderedFiles {
        SymbolNames.requirePackageName(packageName)
        require(catalogs.isNotEmpty()) { "At least one symbol catalog is required" }
        catalogs.keys.forEach { name ->
            SymbolNames.requireTypeIdentifier(name, "catalog name")
            require(name != EntryTypeName) {
                "Catalog name conflicts with generated entry type: $name"
            }
        }
        requireDistinctJvmGetterNames(catalogs.keys)

        var chunkIndex = 0
        val contents = buildString {
            appendLine(
                """
                // Generated by Symbols. DO NOT EDIT.
                @file:Suppress("LargeClass", "MagicNumber")
                package $packageName

                internal data class $EntryTypeName(
                    val name: String,
                    val codePoint: Int,
                )
                """.trimIndent(),
            )

            catalogs.toSortedMap().forEach { (name, catalog) ->
                val chunkFunctions = catalog.entries
                    .chunked(entriesPerChunk)
                    .map { entries ->
                        val functionName =
                            "symbolCatalogChunk${chunkIndex.toString().padStart(3, '0')}"
                        chunkIndex += 1
                        appendLine()
                        appendLine("private fun $functionName(): List<$EntryTypeName> = listOf(")
                        entries.forEach { entry ->
                            appendLine("    $EntryTypeName(\"${entry.name}\", 0x${entry.codePoint.toString(16).uppercase()}),")
                        }
                        appendLine(")")
                        functionName
                    }

                appendLine()
                appendLine(
                    """
                    internal val $name: List<$EntryTypeName> by lazy {
                        buildList(${catalog.entries.size}) {
                    """.trimIndent(),
                )
                chunkFunctions.forEach { functionName ->
                    appendLine("        addAll($functionName())")
                }
                appendLine(
                    """
                        }
                    }
                    """.trimIndent(),
                )
            }
        }

        val path = "${packageName.replace('.', '/')}/SymbolCatalogs.generated.kt"
        return RenderedFiles(mapOf(path to contents))
    }

    private companion object {
        private const val EntryTypeName: String = "SymbolCatalogEntry"

        private fun requireDistinctJvmGetterNames(names: Collection<String>) {
            val collisions = names
                .groupBy { name -> "get${name.replaceFirstChar(Char::uppercaseChar)}" }
                .filterValues { collidingNames -> collidingNames.size > 1 }
            require(collisions.isEmpty()) {
                "Generated catalog JVM getter collisions: " +
                    collisions.entries
                        .sortedBy(Map.Entry<String, List<String>>::key)
                        .joinToString("; ") { (getter, collidingNames) ->
                            "$getter <- ${collidingNames.sorted().joinToString()}"
                        }
            }
        }
    }
}
